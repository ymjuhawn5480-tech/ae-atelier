def add_page_number(canvas, doc):
    canvas.saveState()
    page = canvas.getPageNumber()
    if page > 1:
        canvas.setFont("Korean", 8)
        canvas.drawCentredString(
            A4[0] / 2,
            14 * mm,
            f"- {page - 1} -",
        )
        canvas.drawString(
            20 * mm,
            14 * mm,
            "무용과 타 예술 분야의 영향 및 미래 협업 전망",
        )
    canvas.restoreState()


